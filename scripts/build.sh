#!/bin/bash
# Builds dist/Cleaner.app with swiftc (no Xcode needed: Command Line Tools are enough).
#   scripts/build.sh
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
VERSION="$(cat "$ROOT/VERSION")"
APP="$ROOT/dist/Cleaner.app"

# With only the Command Line Tools, the macOS 27 SDK turns @State into a macro whose plugin
# ships with Xcode alone; the 26.x SDK builds the same app for macOS 14 and later.
SDK_ARGS=()
# Asked as "only the Command Line Tools?": Xcode is not always Xcode.app (Xcode_26.0.app on
# the Actions runners), and an ls that finds nothing must not stop the script under pipefail.
if xcode-select -p | grep -q CommandLineTools; then
    SDK="$(ls -d /Library/Developer/CommandLineTools/SDKs/MacOSX26.*.sdk 2>/dev/null | sort -V | tail -1 || true)"
    # An if, not `[ … ] && …`: bash 3.2 (macOS) exits under set -e when that is the
    # last command of the block and the test is false.
    if [ -n "$SDK" ]; then SDK_ARGS=(-sdk "$SDK"); fi
fi
mkdir -p "$ROOT/.build"

# The helper and the app check each other's signature: requirements built from the signing
# certificate, written into a generated source both compile.
IDENTITY="Cleaner Local Signing"
# `|| true`: without the certificate (a fresh clone, CI) security exits 44, and pipefail
# would stop the build instead of falling back to ad hoc.
CERT_SHA1="$(security find-certificate -c "$IDENTITY" -Z 2>/dev/null | awk '/SHA-1/ {print $3}' || true)"
if [ -n "$CERT_SHA1" ]; then ANCHOR=" and certificate leaf = H\\\"$CERT_SHA1\\\""; else ANCHOR=""; fi
cat > "$ROOT/.build/HelperRequirement.swift" <<SWIFT
// Generated by scripts/build.sh from the signing certificate. Do not edit.
enum HelperRequirement {
    static let client = "identifier \\"click.ciromaciel.cleaner\\"$ANCHOR"
    static let helper = "identifier \\"click.ciromaciel.cleaner.helper\\"$ANCHOR"
}
SWIFT

swiftc -O ${SDK_ARGS[@]+"${SDK_ARGS[@]}"} -target arm64-apple-macosx14.0 -parse-as-library -swift-version 5 \
    -module-name Cleaner $(find "$ROOT/Sources/Cleaner" "$ROOT/Sources/Shared" -name '*.swift') "$ROOT/.build/HelperRequirement.swift" \
    -o "$ROOT/.build/Cleaner"
swiftc -O ${SDK_ARGS[@]+"${SDK_ARGS[@]}"} -target arm64-apple-macosx14.0 -swift-version 5 \
    -module-name CleanerHelper $(find "$ROOT/Sources/Helper" "$ROOT/Sources/Shared" -name '*.swift') "$ROOT/.build/HelperRequirement.swift" \
    -o "$ROOT/.build/CleanerHelper"

rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$ROOT/.build/Cleaner" "$APP/Contents/MacOS/Cleaner"
cp "$ROOT/.build/CleanerHelper" "$APP/Contents/MacOS/CleanerHelper"
mkdir -p "$APP/Contents/Library/LaunchDaemons"
cp "$ROOT/scripts/helper.plist" "$APP/Contents/Library/LaunchDaemons/click.ciromaciel.cleaner.helper.plist"
sed "s/__VERSION__/$VERSION/g" "$ROOT/scripts/Info.plist" > "$APP/Contents/Info.plist"
cp -R "$ROOT/Resources/." "$APP/Contents/Resources/"
cp "$ROOT/rules.json" "$APP/Contents/Resources/rules.json"

# Until there is an Apple Developer account (Developer ID + notarization), sign with the local
# certificate from scripts/signing-identity.sh: the same signature on every build keeps Full
# Disk Access granted across updates. Ad hoc only when that certificate is missing.
# Helper first, with its own identifier; then the app around it (no --deep: it would re-sign
# the helper with the app's identity).
if [ -n "$CERT_SHA1" ]; then SIGN="$IDENTITY"; else
    echo "warning: no '$IDENTITY' certificate (scripts/signing-identity.sh); signing ad hoc" >&2
    SIGN="-"
fi
codesign --force --options runtime --identifier click.ciromaciel.cleaner.helper --sign "$SIGN" "$APP/Contents/MacOS/CleanerHelper"
codesign --force --sign "$SIGN" "$APP"
echo "Cleaner $VERSION → $APP"
